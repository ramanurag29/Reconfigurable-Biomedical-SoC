#!/usr/bin/env python3
"""
fir_golden_model.py - bit-exact fixed-point FIR golden model + coefficient generator.

  y[n] = sat11( (sum_{k<T} h[k]*x[n-k] + 2^(S-1)) >> S )      (arithmetic shift, round-half-up)
  x : signed 11b (ECG codes - 512), h : signed 12b Q1.11 (value = h/2048), S = 11, x[n<0] = 0
Design: Hamming-window low-pass, fc = 40 Hz @ 360 Hz (T = 8 and 16). Pure integer arithmetic in
the golden path (no floats), floats are used only for the *design* and for the error report.
Run from repo root after ecg_pipeline.py.
"""
import json, os, sys
import numpy as np
from scipy import signal

MEM, RES = "06_Simulation/mem", "09_Results/fir"
FS, FC, S, XW, HW = 360.0, 40.0, 11, 11, 12
YMAX, YMIN = (1 << (XW - 1)) - 1, -(1 << (XW - 1))

def read_hex_signed(path, bits):
    v = [int(l, 16) for l in open(path).read().split()]
    return np.array([(x - (1 << bits)) if x >= (1 << (bits - 1)) else x for x in v], dtype=np.int64)

def design(taps):
    h = signal.firwin(taps, FC, fs=FS, window="hamming")
    q = np.clip(np.round(h * (1 << (HW - 1))), -(1 << (HW - 1)), (1 << (HW - 1)) - 1).astype(np.int64)
    return h, q

def fir_golden(x, hq, shift=S):
    acc = np.convolve(x.astype(np.int64), hq)[: len(x)]
    y = (acc + ((1 << (shift - 1)) if shift else 0)) >> shift
    sat = int(np.count_nonzero((y > YMAX) | (y < YMIN)))
    return np.clip(y, YMIN, YMAX), sat

def wr(path, vals, bits):
    nh = (bits + 3) // 4
    with open(path, "w") as f:
        f.write("\n".join(f"{int(v) & ((1 << bits) - 1):0{nh}X}" for v in vals) + "\n")

def main():
    os.makedirs(RES, exist_ok=True)
    x = read_hex_signed(f"{MEM}/ecg_signed_11b.hex", XW)
    N = len(x); rep = {"n_samples": int(N), "shift": S, "fc_hz": FC, "fs_hz": FS}
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    fig, ax = plt.subplots(2, 1, figsize=(10, 8))
    for taps in (8, 16):
        h, hq = design(taps)
        y, sat = fir_golden(x, hq)
        yf = signal.lfilter(h, 1.0, x.astype(float))            # float reference (report only)
        err = y - yf
        w, Hf = signal.freqz(h, worN=2048, fs=FS)
        _, Hq = signal.freqz(hq / (1 << (HW - 1)), worN=2048, fs=FS)
        db = lambda H: 20 * np.log10(np.maximum(np.abs(H), 1e-9))
        pb = np.abs(Hq[w <= 25]); sb = np.abs(Hq[w >= 90])
        rep[f"taps{taps}"] = dict(
            coef_q=hq.tolist(), dc_gain=float(hq.sum() / 2048), saturated_outputs=sat,
            y_min=int(y.min()), y_max=int(y.max()),
            rms_err_vs_float_lsb=float(np.sqrt(np.mean(err ** 2))), max_err_vs_float_lsb=float(np.max(np.abs(err))),
            passband_ripple_db_0_25Hz=float(20 * np.log10(pb.max() / pb.min())),
            stopband_worst_gain_db_ge90Hz=float(20 * np.log10(sb.max())),
            gain_db_at_50Hz=float(db(Hq)[np.argmin(np.abs(w - 50))]), y_sum=int(y.sum()))
        wr(f"{MEM}/fir_coef{taps}.hex", hq, HW)
        wr(f"{MEM}/fir_y{taps}.hex", y, XW)
        ax[0].plot(w, db(Hf), label=f"{taps} taps float"); ax[0].plot(w, db(Hq), "--", label=f"{taps} taps Q1.11")
        if taps == 16: ax[1].plot(x[:720], lw=.7, label="input x (codes)"); ax[1].plot(y[:720], lw=.7, label="FIR16 y")
    ax[0].set_ylim(-80, 5); ax[0].set_xlabel("Hz"); ax[0].set_ylabel("dB"); ax[0].legend(); ax[0].grid(alpha=.3)
    ax[0].set_title("FIR low-pass 40 Hz, 8 vs 16 taps (float vs 12-bit Q1.11)")
    ax[1].legend(); ax[1].set_xlabel("sample (first 2 s)")
    fig.tight_layout(); fig.savefig(f"{RES}/fir_response.png", dpi=120)
    json.dump(rep, open(f"{RES}/fir_report.json", "w"), indent=1)
    with open(f"{MEM}/fir_params.vh", "w") as f:
        f.write("// AUTO-GENERATED by fir_golden_model.py\n")
        f.write(f"`define FIR_SHIFT {S}\n")
        for t in (8, 16):
            f.write(f"`define FIR_COEF{t}_FILE \"{MEM}/fir_coef{t}.hex\"\n`define FIR_Y{t}_FILE \"{MEM}/fir_y{t}.hex\"\n")
    for t in (8, 16):
        r = rep[f"taps{t}"]
        print(f"taps={t:2d} dc_gain={r['dc_gain']:.4f} rms_err={r['rms_err_vs_float_lsb']:.3f} LSB sat={r['saturated_outputs']} "
              f"ripple={r['passband_ripple_db_0_25Hz']:.2f} dB  stopband(>=90Hz)={r['stopband_worst_gain_db_ge90Hz']:.1f} dB")
if __name__ == "__main__":
    sys.exit(main())
