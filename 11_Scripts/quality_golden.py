#!/usr/bin/env python3
"""Bit-exact golden model of 04_RTL/controller/quality_est.v + noisy-ECG stimulus (Experiment 6).

Outputs (06_Simulation/mem/):
  q_expected.txt        per-window results for the clean ECG stream (ecg_signed_11b.hex)
  ecg_noisy_10b.hex     3584-sample stimulus: 7 windows of 512 = clean, clean, noise, noise, clipped, flat, baseline
  q_noisy_expected.txt  per-window results for that stimulus
  q_params.vh           defines used by tb_soc
Line format: class flags score p2p mad mean   (hex, mean as 11-bit two's complement)
Also writes 09_Results/quality/quality_report.json. Run from the repo root.
"""
import json, os
import numpy as np

MEM = "06_Simulation/mem"
CFG = dict(win_log2=9, clip_max=4, amp_min=40, noise_k=1, base_max=64)   # = host_regs reset defaults


def quality_windows(x, win_log2=9, clip_max=4, amp_min=40, noise_k=1, base_max=64):
    L = min(max(win_log2, 4), 10)
    W = 1 << L
    out, prev = [], None
    for w in range(len(x) // W):
        s = [int(v) for v in x[w * W:(w + 1) * W]]
        sad = 0
        for v in s:
            if prev is not None:
                sad += abs(v - prev)
            prev = v
        tot = sum(s)
        mean = tot >> L                     # arithmetic shift = floor (matches >>>)
        mad = sad >> L
        p2p = max(s) - min(s)
        clip = sum(1 for v in s if v <= -512 or v >= 511)
        f_clip = clip > clip_max
        f_flat = p2p < amp_min
        f_noise = 16 * mad > p2p * noise_k
        f_base = abs(mean) > base_max
        pen = 2 * f_clip + 2 * f_flat + f_noise + f_base
        cls = 0 if pen == 0 else 1 if pen == 1 else 2
        score = 255 - 80 * f_clip - 80 * f_flat - 48 * f_noise - 32 * f_base
        flags = (f_base << 3) | (f_noise << 2) | (f_flat << 1) | int(f_clip)
        out.append(dict(cls=cls, flags=flags, score=score, p2p=p2p, mad=mad, mean=mean))
    return out


def write_exp(path, res):
    with open(path, "w") as f:
        for r in res:
            f.write(f"{r['cls']:x} {r['flags']:x} {r['score']:02x} {r['p2p']:03x} {r['mad']:03x} {r['mean'] & 0x7FF:03x}\n")


def main():
    raw = [int(l, 16) for l in open(f"{MEM}/ecg_signed_11b.hex") if l.strip()]
    x = np.array([v - 2048 if v >= 1024 else v for v in raw], dtype=np.int64)
    clean = quality_windows(x, **CFG)
    write_exp(f"{MEM}/q_expected.txt", clean)

    W = 512
    rng = np.random.default_rng(7)
    seg = x[:7 * W].copy()
    labels = ["clean", "clean", "gauss_noise_s30", "gauss_noise_s30", "clipped_gain4", "flat_leadoff", "baseline_+150"]
    seg[2 * W:4 * W] += np.round(rng.normal(0, 30, 2 * W)).astype(np.int64)
    seg[4 * W:5 * W] *= 4
    seg[5 * W:6 * W] = np.round(rng.normal(0, 2, W)).astype(np.int64)
    seg[6 * W:7 * W] += 150
    seg = np.clip(seg, -512, 511)
    codes = seg + 512
    with open(f"{MEM}/ecg_noisy_10b.hex", "w") as f:
        f.writelines(f"{c:03X}\n" for c in codes)
    noisy = quality_windows(seg, **CFG)
    write_exp(f"{MEM}/q_noisy_expected.txt", noisy)

    with open(f"{MEM}/q_params.vh", "w") as f:
        f.write("// AUTO-GENERATED by quality_golden.py\n")
        f.write(f"`define Q_NWIN_CLEAN {len(clean)}\n`define Q_NWIN_NOISY {len(noisy)}\n`define Q_NOISY_N {len(codes)}\n")

    os.makedirs("09_Results/quality", exist_ok=True)
    names = ["GOOD", "MODERATE", "POOR"]
    rep = dict(config=CFG, window_samples=W,
               clean=[dict(window=i, quality=names[r["cls"]], **r) for i, r in enumerate(clean)],
               noisy=[dict(window=i, injected=labels[i], quality=names[r["cls"]], **r) for i, r in enumerate(noisy)])
    json.dump(rep, open("09_Results/quality/quality_report.json", "w"), indent=1)
    for tag, res, lab in (("clean", clean, ["clean"] * len(clean)), ("noisy", noisy, labels)):
        for i, r in enumerate(res):
            print(f"{tag} w{i} {lab[i]:16s} -> {names[r['cls']]:8s} score={r['score']:3d} flags={r['flags']:04b} "
                  f"p2p={r['p2p']} mad={r['mad']} mean={r['mean']}")


if __name__ == "__main__":
    main()
